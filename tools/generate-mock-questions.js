function main() {
  const insert = db.prepare(`
    INSERT OR REPLACE INTO questions (id, subject, chapter, type, question, options, answer, explanation, animation_id)
    VALUES (@id, @subject, @chapter, @type, @question, @options, @answer, @explanation, @animation_id)
  `);

  let seq = 0;
  const tx = db.transaction(() => {
    for (const [subjectRaw, items] of Object.entries(BANK)) {
      const subject = subjectRaw.replace(/-补充$/, ''); // 归一化补充科目
      for (const it of items) {
        seq++;
        const id = 'M' + String(seq).padStart(3, '0');
        insert.run({
          id,
          subject,
          chapter: it.c,
          type: '单选',
          question: it.q,
          options: JSON.stringify(it.o),
          answer: JSON.stringify(it.a),
          explanation: it.e,
          animation_id: it.anim,
        });
      }
    }
  });
  tx();

  const total = db.prepare('SELECT COUNT(*) AS n FROM questions').get().n;
  console.log(`✅ 已生成 ${seq} 道高频模拟题`);
  console.log(`📊 题库总数：${total} 道`);
  console.log(`   各科分布：`);
  const subjects = ['408', '数学一', '政治', '英语一'];
  for (const subject of subjects) {
    const n = db.prepare('SELECT COUNT(*) AS n FROM questions WHERE subject = ?').get(subject).n;
    console.log(`     ${subject}: ${n} 道`);
  }
}

main();
