  const pipelines = [
    [4, 5, 10], [5, 4, 8], [6, 3, 12],
  ];
  pipelines.forEach(([k, t, n], i) => {
    arr.push(Q('408', '计算机组成原理', `${k} 段流水线，每段时间 ${t}ns，执行 ${n} 条指令的加速比约为？`, [`约 ${(k * n * t / ((k + n - 1) * t)).toFixed(2)}`, '1', `${k}`, `${n}`], 0, `加速比 = 串行时间/流水时间 = ${k}×${n}×${t} / (${k}+${n}-1)×${t} ≈ ${(k * n / (k + n - 1)).toFixed(2)}。`, i < 2 ? 2022 : 2021, null));
  });
  return arr;
