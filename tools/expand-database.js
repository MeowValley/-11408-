// ---- 408 数据结构：复杂度/遍历/排序/查找 参数化 ----
function genDS() {
  const arr = [];
  // 完全二叉树深度（参数化 n）
  const ns = [100, 200, 500, 1000, 50, 300, 700, 999];
  ns.forEach((n, i) => {
    const d = Math.floor(Math.log2(n)) + 1;
    const opts = [d, d - 1, d + 1, Math.ceil(Math.log2(n))];
    arr.push(Q('408', '数据结构', `具有 ${n} 个结点的完全二叉树的深度（根深度为 1）是？`, opts.map(String), 0, `深度 = ⌊log₂${n}⌋+1 = ⌊${Math.log2(n).toFixed(2)}⌋+1 = ${d}。`, i < 3 ? 2020 : 2021, 'DS-17'));
  });
  // 二叉树 n0=n2+1（参数化）
  const n2s = [10, 20, 50, 100, 30, 80, 15, 45];
  n2s.forEach((n2, i) => {
    arr.push(Q('408', '数据结构', `一棵二叉树有 ${n2} 个度为 2 的结点，则叶子结点数是？`, [`${n2 + 1}`, `${n2}`, `${n2 - 1}`, `${n2 * 2}`], 0, `根据二叉树性质 n₀ = n₂ + 1 = ${n2} + 1 = ${n2 + 1}。`, i < 4 ? 2019 : 2022, 'DS-17'));
  });
  // 完全图边数（参数化）
  const vn = [5, 6, 7, 8, 10, 12];
  vn.forEach((v, i) => {
    const e = v * (v - 1) / 2;
    arr.push(Q('408', '数据结构', `有 ${v} 个顶点的无向完全图，边数是？`, [`${e}`, `${e * 2}`, `${v * v}`, `${v - 1}`], 0, `完全图边数 = n(n-1)/2 = ${v}×${v - 1}/2 = ${e}。`, i < 3 ? 2024 : 2023, null));
  });
  // 排序复杂度（参数化算法名）
  const sorts = [
    ['快速排序', 'O(n log n)', 'O(n²)'],
    ['堆排序', 'O(n log n)', 'O(n²)'],
    ['归并排序', 'O(n log n)', 'O(n²)'],
    ['直接插入排序', 'O(n²)', 'O(n log n)'],
    ['冒泡排序', 'O(n²)', 'O(n log n)'],
    ['简单选择排序', 'O(n²)', 'O(n log n)'],
  ];
  sorts.forEach(([name, correct, wrong], i) => {
    arr.push(Q('408', '数据结构', `${name}的平均时间复杂度是？`, [correct, wrong, 'O(n)', 'O(log n)'], 0, `${name}平均时间复杂度为 ${correct}。${name === '快速排序' ? '最坏情况（基本有序）退化为 O(n²)。' : ''}`, i < 3 ? 2022 : 2020, name === '快速排序' || name === '堆排序' || name === '归并排序' ? 'DS-50' : null));
  });
  // 折半查找比较次数
  const bn = [8, 16, 32, 64, 100, 128];
  bn.forEach((n, i) => {
    const c = Math.floor(Math.log2(n)) + 1;
    arr.push(Q('408', '数据结构', `对 ${n} 个有序元素进行折半查找，最多比较次数是？`, [`${c}`, `${c - 1}`, `${n}`, `${n / 2}`], 0, `折半查找最多比较 ⌊log₂${n}⌋+1 = ${c} 次。`, i < 3 ? 2020 : 2018, null));
  });
  return arr;
}

