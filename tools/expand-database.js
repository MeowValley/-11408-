/* =====================================================================
 * 主流程：汇总所有生成器，插入数据库
 * ===================================================================== */
function main() {
  const all = [
    ...genDS(), ...genCO(), ...genOS(), ...genCN(),
    ...genMath(), ...genMathCalc(), ...genLA(), ...genPolitics(), ...genPolitics2(), ...genEnglish(),
  ];

  const insert = db.prepare(`
    INSERT OR REPLACE INTO questions (id, subject, chapter, type, question, options, answer, explanation, animation_id, is_real_exam, year)
    VALUES (@id, @subject, @chapter, @type, @question, @options, @answer, @explanation, @animation_id, @is_real, @year)
  `);

  // 用现有最大 E 编号继续
  const maxE = db.prepare("SELECT id FROM questions WHERE id LIKE 'E%' ORDER BY id DESC LIMIT 1").get();
  let seq = maxE ? parseInt(maxE.id.replace('E', '')) : 0;

  const tx = db.transaction(() => {
    all.forEach((it) => {
      seq++;
      insert.run({
        id: 'E' + String(seq).padStart(4, '0'),
        subject: it.subject,
        chapter: it.chapter,
        type: it.type || '单选',
        question: it.q,
        options: JSON.stringify(it.o),
        answer: JSON.stringify(it.a),
        explanation: it.e,
        animation_id: it.anim,
        is_real: it.year > 0 ? 1 : 0,
        year: it.year > 0 ? it.year : null,
      });
    });
  });
  tx();

  console.log(`✅ 本轮扩充 ${all.length} 道题`);

  // 统计
  const total = db.prepare('SELECT COUNT(*) AS n FROM questions').get().n;
  const real = db.prepare('SELECT COUNT(*) AS n FROM questions WHERE is_real_exam = 1').get().n;
  console.log(`📊 题库总数：${total} 道，其中真题 ${real} 道`);
  console.log(`\n各科分布：`);
  for (const s of ['408', '数学一', '政治', '英语一']) {
    const n = db.prepare('SELECT COUNT(*) AS n FROM questions WHERE subject = ?').get(s).n;
    console.log(`  ${s}: ${n} 道`);
  }
}

main();
